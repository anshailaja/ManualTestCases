package Virat;

public class Hw1102 {
//Write a program to print the multiplication table from 1 to 5.
	public static void main(String[] args) {
		for(int i=1;i<=5;i++) {
			System.out.println("Multiplication table for i is: " + i + " :");
			for(int j=1;j<=10;j++) {
				System.out.println("Multiplication table for j is: "+ i + " x " + j + " = " +  (i*j));
				
			}
		}
		
		
		
		

	}

}
